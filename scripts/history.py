#   Show the FCB1010 config history and diff any two points in it
#
#   Config content comes from git (every committed version of the plan and
#   read-back CSVs); what happened to the pedal comes from the log
#   (dumps/fcb1010.log.jsonl): sends, dumps, and read-back confirmations.
#
#   Usage:
#     python3 history.py          List the timeline
#     python3 history.py N        Diff entry N against the one before it
#     python3 history.py A B      Diff entry A against entry B
#     python3 history.py load N   Send entry N to the pedal (shows the diff, asks first)
#   Negative indexes count from the end. Bank/Preset numbers match the CSV (1-based).

import subprocess
import sys
import tempfile
from pathlib import Path

from fcb1010 import fcb1010
from fcb_log import ROOT, read_log, sysex_hash

# The device CSVs: "plan" is generated by bank_plan.py, "backup" is a read-back
GIT_FILES = {"FCB1010_bank_plan.csv": "plan", "FCB1010_backup.csv": "backup"}


def git(*args):
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, check=True).stdout


def load_text(text):
    with tempfile.TemporaryDirectory() as d:
        path = Path(d) / "config.csv"
        path.write_text(text)
        fcb = fcb1010()
        return fcb if fcb.load(str(path)) else None


def git_rows():
    """One row per distinct committed version of each device CSV, oldest first."""
    rows, seen = [], set()
    for name, kind in GIT_FILES.items():
        out = git("log", "--follow", "--name-status", "--format=C\t%H\t%aI\t%s", "--", f"dumps/{name}")
        commits, cur = [], None
        for line in out.splitlines():
            if line.startswith("C\t"):
                _, h, ts, subject = line.split("\t", 3)
                cur = {"commit": h, "ts": ts, "subject": subject}
                commits.append(cur)
            elif line.strip() and cur:
                cur["path"] = line.split("\t")[-1]  # path at that commit (handles renames)
        for c in reversed(commits):
            fcb = load_text(git("show", f"{c['commit']}:{c['path']}"))
            if not fcb:
                continue
            digest = sysex_hash(fcb)
            if (kind, digest) in seen:
                continue
            seen.add((kind, digest))
            rows.append({"ts": c["ts"], "kind": kind, "hash": digest, "commit": c["commit"][:7],
                         "subject": c["subject"], "git": (c["commit"], c["path"])})
    return rows


def log_rows():
    rows = []
    for e in read_log():
        rows.append({"ts": e["ts"], "kind": e["action"], "hash": e["sha256"],
                     "commit": "", "subject": e.get("source") or "", "log": e})
    return rows


def timeline():
    rows = sorted(git_rows() + log_rows(), key=lambda r: r["ts"])
    sent = {r["hash"] for r in rows if r["kind"] == "send"}
    read_back = {r["hash"] for r in rows if r["kind"] in ("backup", "dump")}
    pending, last_send, latest = None, None, {}  # send awaiting a matching dump; most recent send; hash -> last row index
    by_hash = {}
    for r in rows:
        if "git" in r:
            by_hash.setdefault(r["hash"], r)
    for i, r in enumerate(rows):
        r["same_as"] = latest.get(r["hash"])
        latest[r["hash"]] = i
        if "log" in r:
            r["fallback"] = by_hash.get(r["hash"])  # committed version with this hash, if any
        if r["kind"] == "send":
            pending = last_send = r
        elif r["kind"] == "dump":
            r["differs"] = bool(last_send) and r["hash"] != last_send["hash"]
            if pending and r["hash"] == pending["hash"]:
                pending["confirmed"] = True
                pending = None
    for r in rows:
        flags = []
        if r["kind"] == "plan":
            if r["hash"] in sent:
                flags.append("sent")
            if r["hash"] in read_back:
                flags.append("read back from pedal")
        elif r["kind"] == "send" and r.get("confirmed"):
            flags.append("confirmed by a later dump")
        elif r["kind"] == "dump" and r.get("differs"):
            flags.append("differs from last send")
        if r.get("same_as") is not None:
            flags.append(f"same as #{r['same_as']}")
        r["flags"] = ", ".join(flags)
    return rows


def load_row(row):
    if "git" in row:
        commit, path = row["git"]
        return load_text(git("show", f"{commit}:{path}"))
    backup = ROOT / row["log"]["backup"]
    if backup.exists():
        return load_text(backup.read_text())
    return load_row(row["fallback"]) if row.get("fallback") else None


def describe(row):
    if "git" in row:
        return git("log", "-1", "--format=%B", row["git"][0]).strip()
    e = row["log"]
    bits = [f"{e['action']} at {e['ts']}", f"source {e.get('source')}", f"port {e.get('port')}",
            f"backup {e.get('backup')}"]
    return ", ".join(bits)


def list_rows(rows):
    if not rows:
        print("Nothing in the timeline yet.")
        return
    for i, r in enumerate(rows):
        flags = f"  [{r['flags']}]" if r["flags"] else ""
        print(f"{i:3}  {r['ts'][:16]}  {r['kind']:<6}  {r['hash'][:8]}  {r['commit']:<7}  {r['subject']}{flags}")


def diff(a, b):
    changes = []
    for name, old in vars(a).items():
        if name != "preset" and old != getattr(b, name):
            changes.append(f"Global: {name} {old} -> {getattr(b, name)}")
    for i, (pa, pb) in enumerate(zip(a.preset, b.preset)):
        for name, old in vars(pa).items():
            new = getattr(pb, name)
            if old != new:
                changes.append(f"Bank {i // 10 + 1} Preset {i % 10 + 1}: {name} {old} -> {new}")
    return changes


def pedal_state_row(rows):
    """The latest row that says what the pedal held: a send, a dump, or a committed read-back."""
    return next((r for r in reversed(rows) if r["kind"] in ("send", "dump", "backup")), None)


def load_entry(rows, index, confirm=input, sender=None):
    """Show what sending rows[index] would change, ask, then send and log it."""
    row = rows[index]
    fcb = load_row(row)
    if not fcb:
        sys.exit("Could not load that entry's content (its backup file is missing).")
    print(f"Entry {index}: {row['ts'][:16]}  {row['kind']}  {row['hash'][:8]}  {row['subject']}")

    state = pedal_state_row(rows)
    current = load_row(state) if state else None
    if current:
        changes = diff(current, fcb)
        print(f"Pedal's last known state: entry {rows.index(state)} ({state['kind']} {state['hash'][:8]})")
        banks = sorted({int(c.split()[1]) for c in changes if c.startswith("Bank")})
        glob = sum(c.startswith("Global") for c in changes)
        if changes:
            print(f"Sending this would change {len(changes)} fields in banks {banks}"
                  + (f" and {glob} global settings" if glob else "") + ":")
        else:
            print("Identical to the pedal's last known state.")
        print("\n".join(changes[:40]))
        if len(changes) > 40:
            print(f"... and {len(changes) - 40} more (python3 history.py {rows.index(state)} {index} for all)")
    else:
        print("No known pedal state to compare against; this overwrites everything.")

    if confirm("Send this config to the pedal? [y/N] ").strip().lower() != "y":
        print("Not sent.")
        return False
    if row.get("git"):
        source = f"git {row['git'][0][:7]}:{row['git'][1]}"
    else:
        source = row["log"]["backup"]
    if sender is None:
        from send_fcb1010 import send_config as sender
    sender(fcb, source)
    return True


def main():
    rows = timeline()
    if len(sys.argv) == 3 and sys.argv[1] == "load":
        try:
            load_entry(rows, int(sys.argv[2]) % len(rows))
        except ZeroDivisionError:
            sys.exit("Nothing in the timeline yet.")
        return
    args = [int(a) for a in sys.argv[1:]]
    if not args:
        list_rows(rows)
        return
    try:
        if len(args) == 1:
            i = args[0] % len(rows)
            if i == 0:
                sys.exit("Entry 0 has no earlier entry to diff against.")
            old, new = rows[i - 1], rows[i]
        else:
            old, new = rows[args[0]], rows[args[1]]
    except (IndexError, ZeroDivisionError):
        sys.exit("No such entry; run without arguments to list them.")

    print(f"{old['ts']} {old['kind']}  ->  {new['ts']} {new['kind']}\n")
    print(f"{describe(new)}\n")
    a, b = load_row(old), load_row(new)
    if not a or not b:
        sys.exit("Could not load one side's content (its backup file is missing).")
    changes = diff(a, b)
    print("\n".join(changes) if changes else "No differences.")


if __name__ == "__main__":
    main()
